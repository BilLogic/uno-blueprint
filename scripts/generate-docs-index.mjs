#!/usr/bin/env node
/**
 * The two index files, generated from the docs themselves.
 *
 * `INDEX.md` at the root routes by TASK — the row an arriving agent matches
 * against the thing it was asked to do. `docs/index.md` lists every document
 * with the summary its own frontmatter states. Neither is hand-maintained,
 * because a hand-maintained index is a second copy of the tree and drifts
 * from it silently: the index still lists the file, so nothing looks wrong
 * until someone opens the link.
 *
 * The routing table IS authored — which task sends you where is editorial
 * judgment and cannot be derived — but it lives in exactly one place,
 * `scripts/repo-config.mjs`, beside the reading paths, and ships into the
 * generated output. Both are this repository's own; this script, which turns
 * them and the docs' frontmatter into the two files, is the same everywhere.
 *
 *   npm run docs:index         # write both files
 *   npm run check:docs-index   # fail on stale, or on a doc with no summary
 *
 * A DOC WITH NO `summary:` IS A FAILURE, not a blank cell. The summary is
 * what an agent reads when deciding whether to open the file; a row reading
 * "(none)" costs the reader the open anyway, so the index would be lying
 * about its own usefulness. The failure names every offending file.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { repoConfig } from './repo-config.mjs'
import { sweep } from './sweep.mjs'

/** Generated, so never read as an input. */
const GENERATED_BASENAME = 'index.md'

/** Task-shaped routing and the reading paths: this repository's, not this script's. */
const { routing: ROUTING, readingPaths: READING_PATHS } = repoConfig.docsIndex

/** Frontmatter as a flat map. Absent block, or absent keys, give `{}`. */
export function frontmatter(source) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(source)
  if (!match) return {}
  const out = {}
  for (const line of match[1].split('\n')) {
    const idx = line.indexOf(':')
    if (idx === -1) continue
    out[line.slice(0, idx).trim()] = line.slice(idx + 1).trim()
  }
  return out
}

/**
 * Every markdown file under `docs/`, minus the ones this script writes, as
 * paths under `docs/`.
 *
 * THE SUBJECT IS THE COMMIT, not the prose sweep, and the difference is the
 * decision records. This index lists EVERY document under `docs/` — the
 * decision records included, which the routing table reaches through their
 * overview — while the `docs` subject deliberately
 * leaves the dated records out, because a sweep that rewrites a decision
 * record falsifies it. Naming that subject here would silently drop a third of
 * the table. `commit` is the honest one for "every document this tree ships
 * under docs/": tracked, plus untracked and not ignored, so a document written
 * and indexed before `git add` is in the table the way its author sees it.
 */
function docFiles(sweptDocs) {
  return sweptDocs.files.map((path) => path.slice('docs/'.length))
}

/** The documents this index is built out of, for `root`. */
export function sweptDocs(root = process.cwd()) {
  return sweep({
    subject: 'commit',
    root,
    what: `markdown under docs/ other than the generated ${GENERATED_BASENAME}`,
    where: (path) =>
      path.startsWith('docs/') && path.endsWith('.md') && basename(path) !== GENERATED_BASENAME,
  })
}

/**
 * `{ protocol, problems }` out of an already-swept subject — the judgement,
 * with no walk in it. `problems` is the reason this script can fail: a document
 * that states no summary.
 *
 * Paths are joined with a forward slash rather than the platform's separator:
 * what a sweep hands back is repo-relative and slash-separated, and what it
 * takes back is the same spelling.
 */
export function collectFrom(swept) {
  const protocol = []
  const problems = []
  for (const path of docFiles(swept)) {
    const source = swept.read(`docs/${path}`)
    if (source === null) continue // listed, then gone before this read
    const fm = frontmatter(source)
    if (!fm.summary) {
      problems.push({ path, missing: 'summary' })
      continue
    }
    protocol.push({ path, summary: fm.summary })
  }
  return { protocol, problems }
}

/**
 * `{ protocol, problems }` for the docs tree under `root` — the working
 * directory by default, because this script's own location says nothing about
 * which tree it is indexing. `swept` is the subject to read, so a caller that
 * already has one hands it in rather than asking for a second walk.
 */
export function collect(root = process.cwd(), swept = sweptDocs(root)) {
  return collectFrom(swept)
}

function rootIndex({ protocol }) {
  return `<!-- GENERATED by scripts/generate-docs-index.mjs — edit the routing table in scripts/repo-config.mjs, or a doc's frontmatter. Never this file. -->

# Where to find things

Route by the task you arrived with. Every document, with what it answers, is
in [docs/index.md](./docs/index.md); what the folders mean is in
[docs/overview.md](./docs/overview.md).

| Task | Go to |
| --- | --- |
${ROUTING.map(([task, target]) => `| ${task} | ${target} |`).join('\n')}

## The five root files

| File | The question it answers |
| --- | --- |
| [README.md](./README.md) | What is this, and why would I want it? |
| [CONTEXT.md](./CONTEXT.md) | What does this word mean? |
| [SETUP.md](./SETUP.md) | How do I get it running? |
| INDEX.md | Where is the thing I need? *(this file, generated)* |
| [AGENTS.md](./AGENTS.md) | I am an agent — what do I read, and what may I not do? |

## Reading paths

${READING_PATHS}

${protocol.length} protocol documents are indexed in [docs/index.md](./docs/index.md).
`
}

function docsIndex({ protocol }) {
  return `<!-- GENERATED by scripts/generate-docs-index.mjs — edit a doc's frontmatter, never this file. -->

# Every document

Summaries come from each document's own frontmatter. What the folders mean is
in [overview.md](./overview.md); routing by task is in
[INDEX.md](../INDEX.md).

Everything listed here is protocol: it states how the package behaves today,
and a statement in it that is wrong is a bug rather than an old position.

| Doc | What it answers |
| --- | --- |
${protocol.map((r) => `| [${r.path}](./${r.path}) | ${r.summary} |`).join('\n')}
`
}

function report(problems) {
  console.error(
    'Every document under docs/ states what it answers in its frontmatter. ' +
      'These do not:\n',
  )
  for (const { path, missing } of problems) {
    console.error(`  docs/${path} — no \`${missing}:\` in frontmatter`)
  }
  console.error(
    `\n${problems.length} document${problems.length === 1 ? '' : 's'}. Add a ` +
      'one-line `summary:` saying what the document answers — see ' +
      'docs/guidelines/documentation.md — then run:\n\n  npm run docs:index\n',
  )
}

function main() {
  const root = process.cwd()
  const collected = collect(root)
  if (collected.problems.length > 0) {
    report(collected.problems)
    process.exit(1)
  }

  const targets = [
    [join(root, 'INDEX.md'), rootIndex(collected), 'INDEX.md'],
    [join(root, 'docs', GENERATED_BASENAME), docsIndex(collected), 'docs/index.md'],
  ]

  if (process.argv.includes('--check')) {
    const stale = targets.filter(([path, next]) => {
      const current = existsSync(path) ? readFileSync(path, 'utf8') : ''
      return current !== next
    })
    if (stale.length > 0) {
      console.error(
        `${stale.map(([, , label]) => label).join(' and ')} ${stale.length === 1 ? 'is' : 'are'} stale — run:\n\n  npm run docs:index\n`,
      )
      process.exit(1)
    }
    console.log(
      `INDEX.md and docs/index.md are current (${collected.protocol.length} protocol documents)`,
    )
    return
  }

  for (const [path, next, label] of targets) {
    writeFileSync(path, next)
    console.log(`wrote ${label}`)
  }
}

// Same guard as scripts/check-standalone.mjs: comparing against a hand-built
// `file://` URL silently no-ops whenever the path needs escaping, so a
// checkout under a directory with a space in its name would run this script
// and have it do nothing, successfully.
const isMain =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)

if (isMain) main()
